# Regenerates sdk/rust/tome-sys/src/bindings.rs from sdk/include/tome/tome.h
# with bindgen (cargo install bindgen-cli; needs libclang and the MinGW
# headers). The output is committed, so building a Rust mod needs neither.
#
#   tools/gen-rust-bindings.sh           rewrite the file
#   tools/gen-rust-bindings.sh --check   fail if it's out of date (tests)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/sdk/rust/tome-sys/src/bindings.rs"
SYSROOT="${MINGW_SYSROOT:-/usr/i686-w64-mingw32/sys-root/mingw}"
BINDGEN="${BINDGEN:-bindgen}"

generate() {
    # Only Tome's own names; enums as newtypes, since a newer Tome may
    # return values this version doesn't know. The layout assertions bindgen
    # adds are checked when building for i686, the only target mods have.
    # The license line first (tools/spdx.py), before bindgen's own header.
    echo '// SPDX-License-Identifier: MIT-0'
    "$BINDGEN" "$ROOT/sdk/include/tome/tome.h" \
        --rust-edition 2024 --rust-target 1.85 \
        --use-core \
        --allowlist-item '(tome|TOME)_.*' \
        --default-enum-style newtype \
        --no-doc-comments \
        --merge-extern-blocks \
        --raw-line '// Generated by tools/gen-rust-bindings.sh from sdk/include/tome/tome.h. Do not edit.' \
        -- --target=i686-pc-windows-gnu -isystem "$SYSROOT/include" -I "$ROOT/sdk/include" \
           -DTOME_NO_LOGF
}

if [[ "${1:-}" == "--check" ]]; then
    if ! diff -u "$OUT" <(generate) >/dev/null; then
        echo "sdk/rust/tome-sys/src/bindings.rs is out of date: run tools/gen-rust-bindings.sh" >&2
        exit 1
    fi
else
    mkdir -p "$(dirname "$OUT")"
    generate >"$OUT"
fi
