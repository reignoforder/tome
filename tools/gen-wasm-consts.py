#!/usr/bin/env python3
"""Writes the enums of tome.h that WebAssembly mods use (results, log
levels, screens, events, ...) for the Wasm SDKs, which can't use tome.h:

- sdk/include/tome/tome_wasm_consts.h, copied as they are, for tome_wasm.h
  (tome.h needs libc headers a wasm32 build doesn't have);
- sdk/rust/wasm/tome-wasm/src/consts.rs, as Rust constants, for the
  tome-wasm crate (events, screens and frame points also as associated
  constants of its Event, UiEvent and FramePoint).

  tools/gen-wasm-consts.py           write them
  tools/gen-wasm-consts.py --check   exit 1 if one isn't current (a test runs this)

Run it after changing tome.h.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "sdk", "include", "tome", "tome.h")
TARGET = os.path.join(ROOT, "sdk", "include", "tome", "tome_wasm_consts.h")
RUST_TARGET = os.path.join(ROOT, "sdk", "rust", "wasm", "tome-wasm", "src", "consts.rs")

# Enums that mean nothing to a Wasm mod (mapped symbols, raw hooks).
SKIP = {"tome_symbol_kind", "tome_hook_phase"}
# Enums the Rust crate has a type for: (type, prefix of its members).
RUST_TYPES = {"tome_event": ("Event", "TOME_EVENT_"), "tome_ui_event": ("UiEvent", "TOME_UI_"),
              "tome_frame_point": ("FramePoint", "TOME_FRAMEPOINT_")}


def read_source():
    with open(SOURCE, encoding="utf-8") as f:
        return f.read()


def enums(text):
    for m in re.finditer(r"typedef enum (\w+) \{.*?\n\} \1;\n", text, re.S):
        if m.group(1) not in SKIP:
            yield m


def generate():
    text = read_source()
    blocks = []
    for m in enums(text):
        # The comment block right above it, if one starts its own line.
        before = text[: m.start()]
        comment = ""
        if before.endswith("*/\n"):
            open_at = before.rfind("/*")
            line_start = before.rfind("\n", 0, open_at) + 1
            if open_at >= 0 and before[line_start:open_at].strip() == "":
                comment = before[line_start:]
        blocks.append(comment + m.group(0))
    lines = [l for l in text.splitlines() if re.match(r"#define (TOME_POPUP_CLOSED|TOME_API_VERSION)\b", l)]
    out = [
        "/* Generated by tools/gen-wasm-consts.py from tome.h: don't edit. */",
        "#pragma once",
        "",
        "/* tome.h's enums for WebAssembly mods (tome_wasm.h). */",
        "",
    ]
    out += lines + [""] if lines else []
    out.append("\n".join(blocks).rstrip("\n"))
    return "\n".join(out) + "\n"


def generate_rust():
    text = read_source()
    out = [
        "// Generated by tools/gen-wasm-consts.py from tome.h: don't edit.",
        "",
        "//! tome.h's enums (sdk/include/tome/tome.h documents each value).",
        "",
        "#![allow(missing_docs)]",
        "",
    ]
    for m in re.finditer(r"#define (TOME_POPUP_CLOSED|TOME_API_VERSION) \(?(-?\d+)\)?", text):
        kind = "i32" if m.group(1) == "TOME_POPUP_CLOSED" else "u32"
        out.append("pub const %s: %s = %s;" % (m.group(1), kind, m.group(2)))
    typed = []
    for m in enums(text):
        members = re.findall(r"^\s+(TOME_\w+)\s*=\s*(-?\d+)", m.group(0), re.M)
        out.append("")
        out.append("// %s" % m.group(1))
        out += ["pub const %s: i32 = %s;" % (name, value) for name, value in members]
        if m.group(1) in RUST_TYPES:
            rust_type, prefix = RUST_TYPES[m.group(1)]
            typed.append("")
            typed.append("impl crate::%s {" % rust_type)
            typed += ["    pub const %s: Self = Self(%s);" % (name[len(prefix):], name)
                      for name, _ in members if name.startswith(prefix)]
            typed.append("}")
    return "\n".join(out + typed) + "\n"


def main():
    targets = [(TARGET, generate()), (RUST_TARGET, generate_rust())]
    if "--check" in sys.argv:
        stale = []
        for path, content in targets:
            try:
                with open(path, encoding="utf-8") as f:
                    current = f.read()
            except OSError:
                current = None
            if current != content:
                stale.append(os.path.relpath(path, ROOT))
        if stale:
            print("out of date: %s: run tools/gen-wasm-consts.py" % ", ".join(stale))
            return 1
        print("the Wasm SDKs' constants are current")
        return 0
    for path, content in targets:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        print("wrote", os.path.relpath(path, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
