"""Generate loader/src/core/upcase_table.inc: the uppercase mapping NTFS
compares file names with, for zip::fold_name (duplicate names in .tome
packages).

usage: python3 -I tools/gen-upcase.py > loader/src/core/upcase_table.inc

NTFS upper-cases each UTF-16 unit through a 64K table made from Unicode's
simple (one-to-one) uppercase mappings, so only the BMP is mapped and a
letter whose uppercase is longer (U+00DF -> "SS") stays as it is. Python's
mappings are from a newer Unicode version than any volume's table; that
can only refuse more names, never let two that collide through.
"""
import sys
import unicodedata


def upper(cp):
    if 0xD800 <= cp <= 0xDFFF:
        return cp
    u = chr(cp).upper()
    if len(u) != 1 or ord(u) > 0xFFFF:
        return cp
    return ord(u)


def main():
    # Runs of (first, last, delta, stride): every stride-th code point in
    # [first, last] maps to itself + delta.
    pairs = [(cp, upper(cp) - cp) for cp in range(0x80, 0x10000) if upper(cp) != cp]
    runs = []
    for cp, delta in pairs:
        if runs:
            first, last, d, stride = runs[-1]
            if d == delta and (cp - last == stride or (first == last and cp - last in (1, 2))):
                runs[-1] = (first, cp, d, cp - last if first == last else stride)
                continue
        runs.append((cp, cp, delta, 1))
    print("// Generated by tools/gen-upcase.py (Unicode %s). Do not edit." % unicodedata.unidata_version)
    print("// {first, last, delta, stride}: non-ASCII BMP code points to their simple uppercase.")
    for first, last, delta, stride in runs:
        print("{0x%04X, 0x%04X, %d, %d}," % (first, last, delta, stride))
    print("%d runs, %d code points" % (len(runs), len(pairs)), file=sys.stderr)


if __name__ == "__main__":
    sys.exit(main())
